# ---------------------------------------------------------------- 1. weekly amortization
h('1. Fixed-term amortizing loans — weekly payments (52/yr)')
def weekly_payment(P, annual_rate, years):
    r = annual_rate / TICKS_PER_YEAR; n = years * TICKS_PER_YEAR
    return P * r / (1 - (1 + r) ** -n)
print('| Principal | Rate | Term | Weekly payment | Total paid | Total interest | Interest ÷ principal |')
