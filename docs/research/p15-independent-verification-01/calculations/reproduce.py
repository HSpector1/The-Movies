HIRING_TERMINATION_FRACTION = 0.5
RIVAL_ARRIVAL_WEEKS = [0, 0, 0, 0, 520, 988, 1560, 1872, 2548]   # src/core/calendar.ts:3
GENRES = ['romance', 'horror', 'comedy', 'adventure', 'drama', 'crime']
